import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
const extract=(a,b)=>html.slice(html.indexOf("      function "+a+"("),html.indexOf("      function "+b+"("));
const hash=new Function(extract("visualSeed","rasterAsset")+";return visualSeed")();
const budget=new Function(extract("visualDetailBudget","planetRingProfile")+";return visualDetailBudget")();
const ring=new Function("visualSeed",extract("planetRingProfile","drawPlanetLighting")+";return planetRingProfile")(hash);
assert.equal(budget({graphics:"Low"}).jumpRays,0);
assert.equal(budget({performanceMode:"Battery Saver",graphics:"High"}).particles,0);
assert.equal(budget({motion:"Reduced"}).jumpRays,0);
assert.equal(budget({graphics:"High"}).rings,30);
assert.ok(budget({graphics:"Medium"}).rings<30);
const body={name:"Vesper",featureSeed:42};
assert.deepEqual(ring(body),ring(body));
assert.notDeepEqual(ring(body),ring({...body,featureSeed:192}));
assert.equal(ring({name:"Saturn",featureSeed:1}).tilt,-.32);
const frame=new Function("clamp","visualDetailBudget",extract("jumpArrivalFrame","startJumpArrival")+";return jumpArrivalFrame")((v,a,b)=>Math.max(a,Math.min(b,v)),budget);
assert.equal(frame(0).fade,1);
assert.ok(frame(425).fade<.5);
assert.equal(frame(850).active,false);
assert.equal(frame(260,{motion:"Reduced"}).active,false);
assert.equal(frame(50,{motion:"Reduced"}).rays,0);
const intersects=new Function(extract("orbitIntersectsViewport","drawOrbit")+";return orbitIntersectsViewport")();
assert.equal(intersects({x:50,y:50},20,100,100),true);
assert.equal(intersects({x:50,y:50},1000,100,100),false);
assert.equal(intersects({x:-100,y:50},150,100,100),true);
assert.equal(intersects({x:-100,y:50},20,100,100),false);
assert.match(extract("startJumpArrival","drawJumpArrival"),/cam\.x=game\.ship\.x/);
assert.match(extract("resetFlightEffects","initGame"),/jumpArrivalFX = null/);
assert.match(extract("jumpSystem","chartedJumpCandidates"),/startJumpArrival\(\)/);
console.log("Final visual refinement: seeded ring profiles, quality budgets, jump duration and orbit culling passed.");

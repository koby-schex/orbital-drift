import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const read = path => readFileSync(new URL(path, root), "utf8");
const html = read("index.html");
const plugin = read("native/ios/OrbitalDriftAdMobPlugin.swift");
const linker = read("scripts/link-ios-ads-sdk.mjs");
const prep = read("scripts/prepare-ios-release.mjs");
const installer = read("scripts/install-ios-storekit.mjs");
const controller = read("native/ios/OrbitalDriftBridgeViewController.swift");
const ci = read(".github/workflows/ios-project.yml");
const dist = read(".github/workflows/ios-distribution.yml");
const between = (name,next) => {
  const a=html.indexOf("      function "+name+"(");
  const b=html.indexOf("      function "+next+"(",a+1);
  assert.ok(a>=0&&b>a);
  return html.slice(a,b);
};
const interstitial = between("canShowInterstitial","updateAdManager");
assert.match(interstitial,/return false/);
assert.doesNotMatch(html,/maybeShowInterstitial\("major_reward"\)/,"Never interrupt a reward with automatic ad");
assert.match(plugin,/user-initiated optional reward|opt-in-only advertisements/);
assert.match(plugin,/ConsentInformation\.shared\.requestConsentInfoUpdate/);
assert.match(plugin,/ConsentForm\.loadAndPresentIfRequired/);
assert.match(plugin,/ConsentInformation\.shared\.canRequestAds/);
assert.match(plugin,/ConsentForm\.presentPrivacyOptionsForm/);
assert.match(plugin,/adDidDismissFullScreenContent/);
assert.match(plugin,/rewardedEarned = true/);
assert.match(plugin,/completed": succeeded && rewardedEarned/);
assert.doesNotMatch(plugin,/showInterstitial/);
assert.match(prep,/IOS_ADMOB_APP_ID/);
assert.match(prep,/IOS_ADMOB_REWARDED_UNIT_ID/);
assert.match(prep,/OrbitalDriftAdsEnabled/);
assert.match(linker,/13\.12\.0/);
assert.match(linker,/3\.1\.0/);
assert.match(linker,/XCRemoteSwiftPackageReference/);
assert.match(linker,/XCSwiftPackageProductDependency/);
assert.match(installer,/OrbitalDriftAdMobPlugin\.swift/);
assert.match(controller,/registerPluginInstance\(OrbitalDriftAdMobPlugin\(\)\)/);
assert.match(ci,/scripts\/link-ios-ads-sdk\.mjs/);
assert.match(dist,/vars\.IOS_ADMOB_APP_ID/);
assert.match(dist,/vars\.IOS_ADMOB_REWARDED_UNIT_ID/);
const privacy = between("openPrivacyOptions","setMenuTab");
assert.match(privacy,/plugin\.privacyOptions\(\)/);
assert.match(privacy,/Privacy options are not available/);
assert.match(html,/Sponsored rewards are unavailable in this build/);
console.log("Privacy-first native ads passed: opt-in-only rewards, consent, denied-unavailable behavior, and SDK wiring.");

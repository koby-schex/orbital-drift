import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const workflow = readFileSync(new URL(".github/workflows/ios-project.yml",root),"utf8");
const prep = readFileSync(new URL("scripts/prepare-ios-release.mjs",root),"utf8");
const render = readFileSync(new URL("scripts/render-ios-app-icon.swift",root),"utf8");
const smoke = readFileSync(new URL("scripts/smoke-ios-simulator.sh",root),"utf8");
assert.match(workflow,/node scripts\/prepare-ios-release\.mjs/);
assert.match(workflow,/Generate native iOS project[\s\S]*node scripts\/prepare-ios-release\.mjs[\s\S]*Compile unsigned iOS Simulator/);
assert.match(workflow,/scripts\/render-ios-app-icon\.swift/);
assert.match(prep,/CFBundleDisplayName/);
assert.match(prep,/CFBundleShortVersionString/);
assert.match(prep,/CFBundleVersion/);
assert.match(prep,/assets\/orbital-drift-icon-512\.png/);
assert.match(prep,/AppIcon\.appiconset/);
assert.match(prep,/Contents\.json/);
assert.match(render,/NSImage\(contentsOfFile: input\)/);
assert.match(render,/size = 1024/);
assert.match(render,/NSColor\(calibratedRed/);
assert.match(smoke,/CFBundleDisplayName/);
assert.match(smoke,/CFBundleShortVersionString/);
assert.match(smoke,/OrbitalDrift-AppIcon-1024\.png/);
console.log("iOS branding and package metadata preflight passed.");

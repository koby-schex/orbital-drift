import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
const extract=(a,b)=>html.slice(html.indexOf("      function "+a+"("),html.indexOf("      function "+b+"("));
const fx=new Function("clamp",extract("flightPresentation","drawShip")+";return flightPresentation")((v,a,b)=>Math.min(b,Math.max(a,v)));
const ship=Object.freeze({orbitLocked:true,lockCharge:100,vx:8,vy:0,fuel:42});
assert.equal(fx(ship,{},false,true).power,1);
assert.equal(fx(ship).wake,.55);
assert.equal(fx({...ship,lockCharge:0}).wake,0);
assert.equal(fx({vx:12,vy:0}).wake,1);
assert.equal(fx({vx:1.6,vy:0}).wake,0);
for(const settings of [{graphics:"Low"},{performanceMode:"Battery Saver"},{motion:"Reduced"}])assert.equal(fx(ship,settings).wake,0);
assert.equal(fx(ship,{graphics:"Low"},true,true).brakeGlow,0);
assert.ok(fx(ship,{},true,true).brakeGlow>0);
assert.ok(fx(ship,{},false,true).pitch>fx({...ship,lockCharge:0},{},false,true).pitch);
assert.equal(fx(ship,{},true,true).pitch,42);
assert.match(extract("drawVelocityField","orbitIntersectsViewport"),/flightPresentation/);
assert.doesNotMatch(extract("drawVelocityField","orbitIntersectsViewport"),/Math.floor\(t/);
assert.match(extract("updateEngineAudio","playSound"),/flightPresentation/);
assert.match(extract("drawJumpArrival","drawScreenFX"),/if\(frame.rays\)/);
assert.match(extract("paintEnvironmentComposition","cinematicSky"),/90\*layout.density/);
console.log("Pass 28: bounded momentum feedback, reduced-motion and battery safeguards, environment and arrival effects passed.");

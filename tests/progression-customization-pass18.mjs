import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
const extract=(a,b)=>html.slice(html.indexOf("      function "+a+"("),html.indexOf("      function "+b+"("));
const bonus=new Function(extract("frontierSurveyBonus","discoveryReward")+";return frontierSurveyBonus")();
assert.deepEqual(bonus({rarity:"Mythic"},{isTutorial:true}),{});
assert.deepEqual(bonus({type:"star",rarity:"Mythic"},{}),{});
assert.deepEqual(bonus({rarity:"Common"},{}),{});
assert.deepEqual(bonus({rarity:"Rare"},{}),{DataCores:3,Crystal:3});
assert.deepEqual(bonus({rarity:"Exotic"},{}),{DataCores:7,Crystal:5});
assert.deepEqual(bonus({rarity:"Mythic"},{}),{DataCores:10,Crystal:8,DarkMatter:1});
const game={monetization:{}},window={};
const mode=new Function("game","window",extract("cosmeticStoreMode","cosmeticPurchaseButton")+";return cosmeticStoreMode")(game,window);
assert.equal(mode(),"web");
window.Capacitor={getPlatform:()=>"ios"};
assert.equal(mode(),"unavailable");
game.monetization.storeKitReady=true;
assert.equal(mode(),"apple");
const rank=new Function(extract("rankCosmetics","renderCosmetics")+";return rankCosmetics")();
const catalog=[{key:"paid",type:"paid"},{key:"earned",type:"achievement"},{key:"owned"},{key:"active"}];
assert.deepEqual(rank(catalog,k=>["owned","active"].includes(k),"active").map(x=>x.key),["active","owned","earned","paid"]);
assert.equal(catalog[0].key,"paid");
assert.match(html,/if \(b\.discoveryRewardClaimed\)/);
assert.match(html,/milestone-meter/);
assert.match(html,/Restore Apple Purchases/);
assert.match(html,/View Apple price/);
console.log("Progression rewards, ownership order and purchase-mode regression passed.");

import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const html=readFileSync(new URL("../index.html",import.meta.url),"utf8");
const extract=(a,b)=>html.slice(html.indexOf("      function "+a+"("),html.indexOf("      function "+b+"("));
const visual=new Function("sectorVisualThemes",extract("systemVisualThemeIndex","sectorVisualTheme")+";return systemVisualThemeIndex")(Array(6).fill({}));
const hash=new Function(extract("visualSeed","rasterAsset")+";return visualSeed")();
const layout=new Function("systemVisualThemeIndex","visualSeed",extract("environmentComposition","paintEnvironmentComposition")+";return environmentComposition")(visual,hash);
const families=["innerForge","gasFrontier","crystalReach","bioCluster","ancientArchive","voidRim"];
const worlds=families.map(key=>({seed:42,archetype:{key}}));
const snapshot=JSON.stringify(worlds);
assert.equal(new Set(worlds.map(s=>layout(s).shape)).size,6);
assert.equal(layout({specialType:"parallel",seed:42}).shape,"rift");
assert.equal(layout({specialType:"cosmicSpirit",seed:42}).shape,"halo");
assert.deepEqual(layout(worlds[0]),layout(worlds[0]));
assert.equal(JSON.stringify(worlds),snapshot);
assert.ok(layout(worlds[5]).density<layout(worlds[4]).density);
assert.doesNotMatch(html,/crew-avatar|crewAvatarHtml|Portrait of /);
const crew=extract("crewDutyLabel","expeditionStagesHtml");
assert.match(crew,/secondaryDetails\("Manage "/);
assert.match(crew,/orbitingFrigate\(\)/);
assert.match(crew,/setCrewDuty/);
assert.match(crew,/upgradeCrew/);
assert.match(crew,/recruitCrew/);
assert.match(crew,/renameCrew/);
assert.doesNotMatch(crew,/Change Uniform/);
assert.match(html,/paintEnvironmentComposition\(c,width,height,environmentComposition/);
console.log("Crew roster and distinct deterministic environment compositions passed.");
